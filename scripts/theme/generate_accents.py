"""Generates Material 3 accent overlays for DarQ from fixed seed colors (light in values, dark in values-night).

Usage: uv run --no-project --with materialyoucolor python scripts/theme/generate_accents.py app/src/main/res
"""
import sys
from materialyoucolor.hct import Hct
from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors as M
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot
from materialyoucolor.scheme.scheme_monochrome import SchemeMonochrome

SEEDS = [("Blue", 0xFF2196F3), ("Teal", 0xFF00897B), ("Green", 0xFF388E3C), ("Purple", 0xFF7E57C2),
         ("Orange", 0xFFEF6C00), ("Rose", 0xFFD81B60), ("Amber", 0xFFFFB300), ("Mono", 0xFF808080)]
ROLES = [("colorPrimary", "primary"), ("colorOnPrimary", "onPrimary"), ("colorPrimaryContainer", "primaryContainer"),
         ("colorOnPrimaryContainer", "onPrimaryContainer"), ("colorPrimaryInverse", "inversePrimary"),
         ("colorSecondary", "secondary"), ("colorOnSecondary", "onSecondary"), ("colorSecondaryContainer", "secondaryContainer"),
         ("colorOnSecondaryContainer", "onSecondaryContainer"), ("colorTertiary", "tertiary"), ("colorOnTertiary", "onTertiary"),
         ("colorTertiaryContainer", "tertiaryContainer"), ("colorOnTertiaryContainer", "onTertiaryContainer"),
         ("android:colorBackground", "background"), ("colorOnBackground", "onBackground"), ("colorSurface", "surface"),
         ("colorOnSurface", "onSurface"), ("colorSurfaceVariant", "surfaceVariant"), ("colorOnSurfaceVariant", "onSurfaceVariant"),
         ("colorSurfaceInverse", "inverseSurface"), ("colorOnSurfaceInverse", "inverseOnSurface"), ("colorOutline", "outline"),
         ("colorOutlineVariant", "outlineVariant"), ("colorSurfaceBright", "surfaceBright"), ("colorSurfaceDim", "surfaceDim"),
         ("colorSurfaceContainerLowest", "surfaceContainerLowest"), ("colorSurfaceContainerLow", "surfaceContainerLow"),
         ("colorSurfaceContainer", "surfaceContainer"), ("colorSurfaceContainerHigh", "surfaceContainerHigh"),
         ("colorSurfaceContainerHighest", "surfaceContainerHighest")]

def hexc(argb):
    return "#%06X" % (argb & 0xFFFFFF)

def write(path, dark):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by scripts/theme/generate_accents.py from fixed seeds. Regenerate instead of editing by hand. -->", "<resources>"]
    for name, seed in SEEDS:
        cls = SchemeMonochrome if name == "Mono" else SchemeTonalSpot
        scheme = cls(Hct.from_int(seed), dark, 0.0, spec_version="2021")
        out.append(f'    <style name="ThemeOverlay.Darq.Accent.{name}" parent="">')
        for attr, role in ROLES:
            out.append(f'        <item name="{attr}">{hexc(getattr(M, role).get_argb(scheme))}</item>')
        out.append("    </style>")
    out.append("</resources>")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

write(sys.argv[1] + "/values/theme_accents.xml", False)
write(sys.argv[1] + "/values-night/theme_accents.xml", True)
