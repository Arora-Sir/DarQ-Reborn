"""Generates the Pure black surface lift overlays for DarQ (values/theme_pure_black.xml).

Usage: python scripts/theme/generate_pure_black.py app/src/main/res

The ladder matches components/theme/PureBlackLift.kt and the DualClone surface lift in the blueprint.
Each surface is interpolated through three anchors, flat (lift 0), recommended (lift 50) and lifted (lift 100).
The page stays #000000 and every grey is neutral. Level 5 of 10 is also ThemeOverlay.Darq.PureBlack.
"""
import sys

# (flat, recommended, lifted) grey level of each surface role
CONTAINER = (4, 13, 27)
HIGH = (8, 22, 42)
HIGHEST = (12, 31, 52)
DEFAULT_LIFT = 50


def step(anchors, lift):
    flat, recommended, lifted = anchors
    if lift <= 50:
        value = flat + (recommended - flat) * lift / 50
    else:
        value = recommended + (lifted - recommended) * (lift - 50) / 50
    return max(0, min(255, int(value + 0.5)))


def grey(level):
    return "#FF%02X%02X%02X" % (level, level, level)


def overlay(name, lift):
    container = step(CONTAINER, lift)
    low = max(0, int(container / 2 + 0.5))
    lines = [
        f'    <style name="{name}" parent="">',
        '        <item name="android:colorBackground">@android:color/black</item>',
        '        <item name="colorSurface">@android:color/black</item>',
        '        <item name="colorSurfaceDim">@android:color/black</item>',
        '        <item name="colorSurfaceContainerLowest">@android:color/black</item>',
        f'        <item name="colorSurfaceContainerLow">{grey(low)}</item>',
        f'        <item name="colorSurfaceContainer">{grey(container)}</item>',
        f'        <item name="colorSurfaceContainerHigh">{grey(step(HIGH, lift))}</item>',
        f'        <item name="colorSurfaceContainerHighest">{grey(step(HIGHEST, lift))}</item>',
        "    </style>",
    ]
    return lines


out = ['<?xml version="1.0" encoding="utf-8"?>',
       "<!-- Generated by scripts/theme/generate_pure_black.py. Regenerate instead of editing by hand. -->",
       "<resources>"]
for level in range(0, 11):
    out += overlay(f"ThemeOverlay.Darq.PureBlack.Lift{level}", level * 10)
out += overlay("ThemeOverlay.Darq.PureBlack", DEFAULT_LIFT)
out.append("</resources>")
open(sys.argv[1] + "/values/theme_pure_black.xml", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
